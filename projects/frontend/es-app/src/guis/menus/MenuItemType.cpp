MenuItemType MenuConverters::ItemFromString(const String& type)
{
  if (MenuItemType* t = sStringToItemType.try_get(type); t != nullptr) return *t;
  { LOG(LogFatal) << "[MenuProvider] Unknown menu item ID " << type; }
  __builtin_unreachable();
}

String MenuConverters::ItemToString(MenuItemType type)
{
  for(const auto& kv : sStringToItemType)
    if (kv.second == type)
      return kv.first;
  return "Unknown";
}

