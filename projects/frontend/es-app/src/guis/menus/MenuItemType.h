class MenuConverters
{
  public:
    /*!
     * @brief Convert a string to a menu container value - May throw fatal error and not return
     * @param type Stringized menu container
     * @return MenuContainerType value
     */
    static MenuContainerType MenuFromString(const String& type);
    /*!
     * @brief Convert a string to a menu item value - May throw fatal error and not return
     * @param type Stringized menu item
     * @return MenuItemType value
     */
    static MenuItemType ItemFromString(const String& type);

    /*!
     * @brief Convert menu item to string for debugging purpose
     * @param type Menu item type
     * @return Menu item type as string
     */
    static String ItemToString(MenuItemType type);
};
