#!/bin/bash
#
# Compiles the Vulkan shaders to SPIR-V and emits them as C arrays in
# ShadersSpv.h, so the build needs no shader compiler at all.
#
# Run this after editing any .vert/.frag here, and commit the regenerated
# header alongside the source change.
#
#   ./genshaders.sh
#
# Requires glslangValidator (Debian/Ubuntu: apt install glslang-tools).
#
set -euo pipefail

cd "$(dirname "$0")"

COMPILER=""
for candidate in glslangValidator glslang; do
  if command -v "$candidate" >/dev/null 2>&1; then COMPILER="$candidate"; break; fi
done
if [[ -z "$COMPILER" ]]; then
  echo "error: glslangValidator not found — install it (apt install glslang-tools)" >&2
  exit 1
fi

OUTPUT="../ShadersSpv.h"
TMPDIR_="$(mktemp -d)"
trap 'rm -rf "$TMPDIR_"' EXIT

# shader source -> C array name
SHADERS=(
  "color.vert:kColorVertSpv"
  "color.frag:kColorFragSpv"
  "texture.vert:kTextureVertSpv"
  "texture.frag:kTextureFragSpv"
  "alpha.frag:kAlphaFragSpv"
)

{
  echo "//"
  echo "// GENERATED by rendering/vulkan/shaders/genshaders.sh — DO NOT EDIT."
  echo "//"
  echo "// Edit the .vert/.frag files in shaders/ and re-run that script instead."
  echo "// Keeping SPIR-V here means the build needs no shader compiler, on any"
  echo "// target or toolchain. See VULKAN.md."
  echo "//"
  echo "#pragma once"
  echo
  echo "#include <cstdint>"
  echo
} > "$OUTPUT"

for entry in "${SHADERS[@]}"; do
  src="${entry%%:*}"
  var="${entry##*:}"
  echo "  compiling $src -> $var"
  "$COMPILER" -V --vn "$var" -o "$TMPDIR_/$var.h" "$src" >/dev/null
  # Keep only the array itself: glslangValidator also emits its own (indented)
  # "#pragma once" and a version comment, both meaningless once concatenated.
  grep -v '#pragma once' "$TMPDIR_/$var.h" \
    | grep -vE '^[[:space:]]*//[[:space:]]*[0-9]+\.' \
    | sed -e 's/[[:space:]]*$//' -e '/./,$!d' >> "$OUTPUT"
  echo >> "$OUTPUT"
done

echo "written: $(cd .. && pwd)/ShadersSpv.h"
