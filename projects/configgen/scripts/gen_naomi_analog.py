#!/usr/bin/env python3
"""Regenerate the naomi/naomi2/atomiswave analog-game set from flycast's own input DB.

A flycast game is "analog" when its InputDescriptors carry an axis section (Full/Half
entries) — driving wheels, Monkey Ball, Samba maracas, etc. Those games read the analog
stick, so on a single-stick controller configgen must route the stick to l_x/l_y instead
of the d-pad (else e.g. Club Kart reads "down" as VIEW instead of steering).

Usage:
    gen_naomi_analog.py <naomi_roms_input.h> <naomi_roms.cpp>
Writes configgen/generators/libretro/naomiAnalogGames.py next to this project.
"""
import os
import re
import sys


def extract(header_path: str, roms_path: str) -> tuple:
    htext = open(header_path).read()
    rtext = open(roms_path).read()
    analog_descriptors = set()
    pedal_descriptors = set()
    for m in re.finditer(r'InputDescriptors\s+(\w+_inputs)\s*=\s*\{(.*?)\n\};', htext, re.S):
        name, body = m.group(1), m.group(2)
        if re.search(r'\b(Full|Half)\b\s*,', body):
            analog_descriptors.add(name)
        # accel/brake pedals are Half axes at index 4 (R2) / 5 (L2).
        if re.search(r'\bHalf\b\s*,\s*[45]\b', body):
            pedal_descriptors.add(name)

    def roms_for(descriptors: set) -> list:
        roms = set()
        for m in re.finditer(r'"([a-z0-9_]+)"\s*,.*?&(\w+_inputs)', rtext, re.S):
            if m.group(2) in descriptors:
                roms.add(m.group(1))
        return sorted(roms)

    return roms_for(analog_descriptors), roms_for(pedal_descriptors)


def _emit(name: str, roms: list) -> list:
    lines = ["%s = frozenset({" % name]
    for i in range(0, len(roms), 6):
        lines.append("    " + ", ".join("'%s'" % r for r in roms[i:i + 6]) + ",")
    lines.append("})")
    return lines


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    analog, pedal = extract(sys.argv[1], sys.argv[2])
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "configgen", "generators", "libretro", "naomiAnalogGames.py")
    lines = ["# Generated by scripts/gen_naomi_analog.py from flycast naomi_roms_input.h.",
             "# Do NOT edit by hand; rerun the generator after a flycast bump.",
             "#",
             "# NAOMI_ANALOG_GAMES: games whose InputDescriptors expose an analog axis (wheel, stick, maracas).",
             "# NAOMI_PEDAL_GAMES:  subset with accel/brake trigger pedals (racing) — need R2/L2 mapped to",
             "#                     face buttons on controllers that lack analog triggers.",
             ""]
    lines += _emit("NAOMI_ANALOG_GAMES", analog)
    lines.append("")
    lines += _emit("NAOMI_PEDAL_GAMES", pedal)
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote %d analog / %d pedal roms to %s" % (len(analog), len(pedal), out))


if __name__ == "__main__":
    main()
